import { supabase } from "./supabase";

export type DirectoryEntry = { student_id: string; display_name: string };
export type MyProfile = DirectoryEntry & { opted_in: boolean };
export type ConnectRequest = {
  id: string;
  sender_id: string;
  recipient_id: string;
  first_message: string;
  status: "pending" | "accepted" | "declined";
  created_at: string;
  sender: DirectoryEntry | null;
  recipient: DirectoryEntry | null;
};
export type ChatMessage = {
  id: string;
  request_id: string;
  sender_id: string;
  body: string;
  created_at: string;
};

function client() {
  if (!supabase) throw new Error("Sign-in is not configured.");
  return supabase;
}

/** The signed-in student's own Connect profile, or null when they have not opted in. */
export async function getMyProfile(): Promise<MyProfile | null> {
  const { data, error } = await client().rpc("my_student_profile");
  if (error) throw new Error(error.message);
  const row = Array.isArray(data) ? data[0] : data;
  return (row as MyProfile | undefined) ?? null;
}

/** Turn Student Connect on (or back on). The student ID is generated by the database. */
export async function optIn(displayName: string): Promise<MyProfile> {
  const { data, error } = await client().rpc("student_opt_in", { p_display_name: displayName });
  if (error) throw new Error(error.message);
  const row = Array.isArray(data) ? data[0] : data;
  if (!row) throw new Error("Could not create your Connect profile.");
  return row as MyProfile;
}

export async function optOut(): Promise<void> {
  const { error } = await client().rpc("student_opt_out");
  if (error) throw new Error(error.message);
}

export async function renameStudent(displayName: string): Promise<void> {
  const { error } = await client().rpc("student_rename", { p_display_name: displayName });
  if (error) throw new Error(error.message);
}

/** Every opted-in student: name + ID only (enforced by database column grants). */
export async function listDirectory(): Promise<DirectoryEntry[]> {
  const { data, error } = await client()
    .from("student_profiles")
    .select("student_id,display_name")
    .eq("opted_in", true)
    .order("display_name");
  if (error) throw new Error(error.message);
  return data ?? [];
}

export async function findByStudentId(studentId: string): Promise<DirectoryEntry | null> {
  const { data, error } = await client()
    .from("student_profiles")
    .select("student_id,display_name")
    .eq("student_id", studentId.trim().toUpperCase())
    .eq("opted_in", true)
    .maybeSingle();
  if (error) throw new Error(error.message);
  return data;
}

/** A directory entry's user_id is never exposed to the client, so requests are sent
 *  through a database function that resolves the student ID and enforces consent. */
export async function sendRequestByStudentId(
  studentId: string,
  message: string,
): Promise<void> {
  const c = client();
  const { error } = await c.rpc("send_student_request", {
    p_student_id: studentId.trim().toUpperCase(),
    p_message: message,
  });
  if (error) throw new Error(error.message);
}

export async function listRequests(): Promise<ConnectRequest[]> {
  const { data, error } = await client().rpc("my_student_requests");
  if (error) throw new Error(error.message);
  return (data ?? []) as unknown as ConnectRequest[];
}

export async function respondToRequest(id: string, status: "accepted" | "declined"): Promise<void> {
  const { error } = await client().from("student_requests").update({ status }).eq("id", id);
  if (error) throw new Error(error.message);
}

export async function listMessages(requestId: string): Promise<ChatMessage[]> {
  const { data, error } = await client()
    .from("student_messages")
    .select("id,request_id,sender_id,body,created_at")
    .eq("request_id", requestId)
    .order("created_at", { ascending: true });
  if (error) throw new Error(error.message);
  return data ?? [];
}

export async function sendMessage(requestId: string, body: string): Promise<void> {
  const c = client();
  const uid = (await c.auth.getUser()).data.user?.id;
  if (!uid) throw new Error("Not signed in.");
  const { error } = await c
    .from("student_messages")
    .insert({ request_id: requestId, sender_id: uid, body });
  if (error) throw new Error(error.message);
}

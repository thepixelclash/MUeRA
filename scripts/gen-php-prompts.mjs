// Generates hosting/php-api/prompts.php from the SYSTEM prompts in src/lib/ai.server.ts so they never drift.
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync("src/lib/ai.server.ts", "utf8");
const m = src.match(/const SYSTEM: Record<string, string> = (\{[\s\S]*?\n\});/);
if (!m) throw new Error("SYSTEM map not found");
const obj = Function(`"use strict"; return (${m[1]})`)();
const esc = (s) => "'" + s.replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";
let out = "<?php\n// GENERATED by scripts/gen-php-prompts.mjs from src/lib/ai.server.ts. Do not edit by hand.\nreturn [\n";
for (const [k, v] of Object.entries(obj)) out += `  ${esc(k)} => ${esc(v)},\n`;
out += "];\n";
writeFileSync("hosting/php-api/prompts.php", out);
console.log("modes:", Object.keys(obj).join(","));
